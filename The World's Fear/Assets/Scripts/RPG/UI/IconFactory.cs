        public static Sprite Get(string key, Color color)
        {
            if (string.IsNullOrEmpty(key) || !Has(key)) return null;
            string ck = key + ColorUtility.ToHtmlStringRGB(color);
            if (cache.TryGetValue(ck, out var s) && s) return s;
            var tpl = key == "rotr" ? Mirror(templates["rotl"]) : templates[key];
            const int n = 16;
            var px = new Color[n * n];
            Color light = Color.Lerp(color, Color.white, 0.55f), dark = Color.Lerp(color, Color.black, 0.45f);
            for (int y = 0; y < n; y++)
            for (int x = 0; x < n; x++)
            {
                char ch = Char(tpl, x, y);
                px[(n - 1 - y) * n + x] = ch == '#' ? color : ch == '+' ? light : ch == '-' ? dark : ch == '>' ? light : Color.clear;
            }
            // Outline.
            var outlined = (Color[])px.Clone();
            var outline = new Color(0.06f, 0.05f, 0.06f, 1f);
            for (int y = 0; y < n; y++)
            for (int x = 0; x < n; x++)
            {
                if (px[y * n + x].a > 0f) continue;
                bool near = (x > 0 && px[y * n + x - 1].a > 0f) || (x < n - 1 && px[y * n + x + 1].a > 0f)
                            || (y > 0 && px[(y - 1) * n + x].a > 0f) || (y < n - 1 && px[(y + 1) * n + x].a > 0f);
                if (near) outlined[y * n + x] = outline;
            }
            var tex = GameAssets.NewTexture(n, n);
            tex.SetPixels(outlined);
            tex.Apply();
            s = Sprite.Create(tex, new Rect(0, 0, n, n), new Vector2(0.5f, 0.5f), 16);
            cache[ck] = s;
            return s;
        }

        static char Char(string[] tpl, int x, int y) => y < tpl.Length && x < tpl[y].Length ? tpl[y][x] : '.';

        static string[] Mirror(string[] t)
        {
            var r = new string[t.Length];
            for (int i = 0; i < t.Length; i++)
            {
                var arr = t[i].ToCharArray();
                System.Array.Reverse(arr);
                r[i] = new string(arr);
            }
            return r;
        }

        public static bool Has(string key) => key == "rotr" || templates.ContainsKey(key);

        // Pick an icon for a skill or passive from its name.
        public static string KeyFor(string id, string name)
        {
            string s = ((id ?? "") + " " + (name ?? "")).ToLowerInvariant();
            if (s.Contains("meteor")) return "meteor";
            if (s.Contains("rain") || s.Contains("barrage") || s.Contains("volley") || s.Contains("multishot")) return "rain";
            if (s.Contains("whirl")) return "spiral";
            if (s.Contains("fire") || s.Contains("ignite") || s.Contains("burn") || s.Contains("power")) return "fire";
            if (s.Contains("frost") || s.Contains("nova") && s.Contains("m_") || s.Contains("blizzard") || s.Contains("chill") || s.Contains("trap")) return s.Contains("trap") ? "trap" : "frost";
            if (s.Contains("storm") || s.Contains("thunder") || s.Contains("static") || s.Contains("zap")) return "bolt";
            if (s.Contains("venom") || s.Contains("poison")) return "poison";
            if (s.Contains("orb") || s.Contains("arcane") || s.Contains("focus") || s.Contains("mind")) return "arcane";
            if (s.Contains("blink") || s.Contains("roll") || s.Contains("charge") || s.Contains("swift") || s.Contains("nimble") || s.Contains("quick")) return "dash";
            if (s.Contains("leap") || s.Contains("shatter") || s.Contains("pound")) return "leap";
            if (s.Contains("cry") || s.Contains("berserk") || s.Contains("unstoppable") || s.Contains("rage")) return "up";
            if (s.Contains("shield") || s.Contains("barrier") || s.Contains("hardened") || s.Contains("skin")) return "shield";
            if (s.Contains("blood") || s.Contains("survivor") || s.Contains("vitality") || s.Contains("heal")) return "heal";
            if (s.Contains("execut") || s.Contains("explosive")) return "skull";
            if (s.Contains("eagle") || s.Contains("hunter")) return "eye";
            if (s.Contains("pierce") || s.Contains("sharp") || s.Contains("arrow")) return "bow";
            if (s.Contains("cleave") || s.Contains("mastery")) return "slash";
            return "arcane";
        }

        public static string WeaponKey(string classId) => classId == "ranger" ? "bow" : classId == "mage" ? "staff" : "sword";
    }
